"""Regenerates samples/: the sample legal outputs required by the hackathon deliverables.

  cd backend && .venv/bin/python scripts/make_samples.py
"""

from __future__ import annotations

import json
import sys
from datetime import date, datetime, UTC
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.agents import reviewer  # noqa: E402
from app.drafting.notices import (  # noqa: E402
    CertificateRequest,
    DemandRequest,
    bsa_certificate_part_a,
    demand_notice,
)
from app.export.docx_export import to_docx  # noqa: E402
from app.export.redline import redline  # noqa: E402
from app.models import TermSheet  # noqa: E402
from app.pipeline import build  # noqa: E402

TODAY = date(2026, 11, 3)
OUT = ROOT.parent / "samples"
FIX = ROOT / "tests" / "fixtures"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    index = ["# Sample outputs", "", f"Generated by `backend/scripts/make_samples.py` on {TODAY.isoformat()} from the "
             "fixtures in `backend/tests/fixtures`. Names, addresses and identifiers are fictional.", ""]

    for name, label in (("freelance_msme", "Service agreement with milestone escrow (micro-enterprise supplier)"),
                        ("nda_mutual", "Mutual non-disclosure agreement"),
                        ("appointment_fte", "Fixed-term appointment letter under the Labour Codes")):
        ts = TermSheet.model_validate_json((FIX / f"{name}.json").read_text())
        r = build(ts, TODAY)
        stem = r["title"].lower().replace(" ", "-")
        (OUT / f"{stem}.md").write_text(r["text"])
        (OUT / f"{stem}.docx").write_bytes(to_docx(r["text"], r["document_hash"]))
        checks = "\n".join(f"- **{f['severity']}** {f['title']}" for f in r["findings"])
        (OUT / f"{stem}.checks.md").write_text(
            f"# Legal checks: {r['title']}\n\nSHA-256 {r['document_hash']}\n\nVerification: "
            f"{r['verification']['passed']}/{r['verification']['total']} consistency checks pass.\n\n{checks}\n")
        if r["escrow"]:
            (OUT / f"{stem}.escrow.json").write_text(json.dumps(
                {"constructor_args": r["escrow"]["constructor_args"], "clause_map": r["escrow"]["clause_map"]}, indent=2))
        index.append(f"- **{label}**: [{stem}.md]({stem}.md), [Word]({stem}.docx), [checks]({stem}.checks.md)"
                     + (f", [escrow settings]({stem}.escrow.json)" if r["escrow"] else ""))

    # Redline: the client asks for 30-day payment and 12-month non-solicit removed.
    base = json.loads((FIX / "freelance_msme.json").read_text())
    new = {**base, "payment_days": 15, "non_solicit_months_after_term": 0}
    a = build(TermSheet.model_validate(base), TODAY)["text"]
    b = build(TermSheet.model_validate(new), TODAY)["text"]
    rl = redline(a, b)
    lines = ["# Redline: payment term shortened, non-solicitation removed", ""]
    for c in rl["clauses"]:
        if c["status"] == "unchanged":
            continue
        lines += [f"## {c['heading']} ({c['status']})", ""]
        lines.append(" ".join(
            f"~~{o['text']}~~" if o["op"] == "del" else f"**{o['text']}**" if o["op"] == "ins" else o["text"]
            for o in c["ops"]))
        lines.append("")
    (OUT / "redline.md").write_text("\n".join(lines))
    index.append("- **Redline between two versions**: [redline.md](redline.md)")

    # MSME payment recovery.
    sup = base["provider"]
    req = DemandRequest(supplier=sup, buyer=base["client"], invoices=[
        {"number": "PN-2026-014", "amount_paise": 15_000_000, "accepted_on": "2026-10-08", "agreed_days": 30},
        {"number": "PN-2026-019", "amount_paise": 3_500_000, "accepted_on": "2026-10-20", "agreed_days": 15},
    ], paid_on="2027-01-31", agreement_reference="the Service Agreement dated 10 November 2026")
    (OUT / "msme-demand-notice.md").write_text(demand_notice(req, TODAY)["text"])
    index.append("- **MSME delayed-payment demand notice with section 16 interest**: [msme-demand-notice.md](msme-demand-notice.md)")

    # BSA s.63 certificate (Part A) for the service agreement.
    svc = build(TermSheet.model_validate(base), TODAY)
    cert = bsa_certificate_part_a(CertificateRequest(
        document_title="Service Agreement between Kaveri Organics Private Limited and Pixelnest Studio",
        document_hash=svc["document_hash"], certifier_name="Ravi Teja", certifier_role="Proprietor, Pixelnest Studio",
        chain="Sepolia test network", escrow_address="0x" + "c0ffee" * 6 + "c0ff"),
        datetime(2026, 11, 10, 6, 30, tzinfo=UTC))
    (OUT / "bsa-63-certificate-part-a.md").write_text(cert)
    index.append("- **Draft BSA s.63(4) certificate, Part A**: [bsa-63-certificate-part-a.md](bsa-63-certificate-part-a.md)")

    # Review of a one-sided contract received from a client.
    text = (ROOT.parent / "evals" / "sample_counterparty_contract.txt").read_text()
    rv = reviewer.review(text, "the service provider", use_llm=False)
    lines = ["# Review of a contract received from a client", "", "Rule layer only (no AI key used).", ""]
    for i in rv["issues"]:
        own = rv["clauses"][i["clause"]].split(".", 1)[0].strip()
        label = f"Clause {own}" if own.isdigit() else f"Paragraph {i['clause'] + 1}"
        cites = "; ".join(f"{c['authority']} {c['provision']}" for c in i["citations"])
        lines += [f"## {label}: {i['risk']} risk", "", f"> {rv['clauses'][i['clause']][:300]}", "",
                  i["issue"], "", f"**Ask for:** {i['suggested_change']}", "", f"Authorities: {cites}", ""]
    (OUT / "review-report.md").write_text("\n".join(lines))
    index.append("- **Review of a one-sided contract**: [review-report.md](review-report.md)")

    (OUT / "README.md").write_text("\n".join(index) + "\n")
    print("\n".join(index))


if __name__ == "__main__":
    main()
